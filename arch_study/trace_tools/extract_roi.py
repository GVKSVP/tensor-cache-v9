#!/usr/bin/env python3
"""
extract_roi.py - turn the raw gem5 L2/L3 request traces of one trace run into
compact, labelled ROI-only tables.

Input  (run dir): l2_trace.trc.gz, l3_trace.trc.gz (MemTraceProbe protobuf),
                  stats.txt (ROI = first stats block); tensor_map.csv from run_map.py
                  (in --maps/<run>/ or the run dir); ptable_ckpt/m5.cpt (page table,
                  written by run_ptable.py, also in --maps/<run>/) to turn the physical addresses
                  the caches see back into program (virtual) addresses
Output (run dir): l2_roi.parquet, l3_roi.parquet with columns
   seq, tick, cmd, cmd_name, line (physical addr >> 6), offset, size, flags, pkt_id,
   pc, vaddr,
   tensor_idx, tensor, role
   plus roi_summary.json (counts per role and per command, coverage).

Addresses outside every tensor are labelled program_image / heap_other /
mmap_other / stack. Raw traces are kept.
"""

import argparse
import csv
import json
import sys
from bisect import bisect_right
from collections import Counter
from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import packet_pb2  # noqa: E402  (generated by protoc from gem5 src/proto/packet.proto)
import protolib  # noqa: E402  (copied from gem5 util/)

MMAP_BASE = 0x4000000000000000
STACK_MIN = 0x7000000000000000  # stack sits at the top of the address space
CHUNK = 1 << 20

CMD_NAMES = {}


def load_cmd_names():
    """Command names in MemCmd::commandInfo order (gem5 src/mem/packet.cc)."""
    import re
    text = (Path.home() / "gem5" / "src" / "mem" / "packet.cc").read_text()
    body = text[text.index("MemCmd::commandInfo[]"):]
    body = body[:body.index("};")]
    for i, name in enumerate(re.findall(r'"([A-Za-z]+)"\s*}', body)):
        CMD_NAMES[i] = name


PAGE_SHIFT = 12


def load_ptable(cpt):
    """physical page -> virtual page, from the [*.workload.ptable.EntryN] sections."""
    p2v = {}
    vaddr = None
    for line in open(cpt):
        if line.startswith("vaddr="):
            vaddr = int(line[6:])
        elif line.startswith("paddr=") and vaddr is not None:
            p2v[int(line[6:]) >> PAGE_SHIFT] = vaddr >> PAGE_SHIFT
            vaddr = None
    return p2v


def roi_window(stats):
    sim = fin = None
    block = 0
    for line in open(stats):
        if "Begin Simulation Statistics" in line:
            block += 1
            if block > 1:
                break
        p = line.split()
        if len(p) > 1 and p[0] == "simTicks":
            sim = int(p[1])
        elif len(p) > 1 and p[0] == "finalTick":
            fin = int(p[1])
    return fin - sim, fin


def load_map(map_csv, brk0):
    rows = list(csv.DictReader(open(map_csv)))
    rows = [r for r in rows if r["role"] != "flush"]
    rows.sort(key=lambda r: int(r["start"]))
    starts = [int(r["start"]) for r in rows]
    return rows, starts


def classify(addr, rows, starts, brk0):
    i = bisect_right(starts, addr) - 1
    if i >= 0 and addr < int(rows[i]["end"]):
        r = rows[i]
        return int(r["idx"]), r["name"], r["role"]
    if addr < brk0:
        return -1, "program_image", "program_image"
    if addr >= STACK_MIN:
        return -1, "stack", "stack"
    if addr >= MMAP_BASE:
        return -1, "mmap_other", "other"
    return -1, "heap_other", "other"


SCHEMA = pa.schema([
    ("seq", pa.uint32()), ("tick", pa.uint64()), ("cmd", pa.uint8()),
    ("cmd_name", pa.string()), ("line", pa.uint64()), ("offset", pa.uint8()),
    ("size", pa.uint16()), ("flags", pa.uint32()), ("pkt_id", pa.uint64()),
    ("pc", pa.uint64()), ("vaddr", pa.uint64()), ("tensor_idx", pa.int16()), ("tensor", pa.string()),
    ("role", pa.string()),
])


def extract(trace, out, t0, t1, rows, starts, brk0, p2v):
    f = protolib.openFileRd(str(trace))
    if f.read(4).decode() != "gem5":
        raise RuntimeError(f"{trace}: not a gem5 trace")
    hdr = packet_pb2.PacketHeader()
    protolib.decodeMessage(f, hdr)
    pkt = packet_pb2.Packet()
    cols = {k: [] for k in SCHEMA.names}
    writer = pq.ParquetWriter(str(out), SCHEMA, compression="zstd")
    roles, cmds = Counter(), Counter()
    seq = total = 0
    cache = {}
    while protolib.decodeMessage(f, pkt):
        total += 1
        tick = pkt.tick
        if tick < t0:
            continue
        if tick > t1:
            break
        addr = pkt.addr
        line = addr >> 6
        vpage = p2v.get(addr >> PAGE_SHIFT)
        vaddr = (vpage << PAGE_SHIFT) | (addr & 4095) if vpage is not None else 0
        lab = cache.get(line)
        if lab is None:
            lab = classify(vaddr, rows, starts, brk0) if vpage is not None \
                else (-1, "unmapped", "other")
            if len(cache) < 4_000_000:
                cache[line] = lab
        cname = CMD_NAMES.get(pkt.cmd, str(pkt.cmd))
        cols["seq"].append(seq)
        cols["tick"].append(tick)
        cols["cmd"].append(pkt.cmd)
        cols["cmd_name"].append(cname)
        cols["line"].append(line)
        cols["offset"].append(addr & 63)
        cols["size"].append(pkt.size)
        cols["flags"].append(pkt.flags)
        cols["pkt_id"].append(pkt.pkt_id)
        cols["pc"].append(pkt.pc if pkt.HasField("pc") else 0)
        cols["vaddr"].append(vaddr)
        cols["tensor_idx"].append(lab[0])
        cols["tensor"].append(lab[1])
        cols["role"].append(lab[2])
        roles[lab[2]] += 1
        cmds[cname] += 1
        seq += 1
        if len(cols["seq"]) >= CHUNK:
            writer.write_table(pa.table(cols, schema=SCHEMA))
            cols = {k: [] for k in SCHEMA.names}
    if cols["seq"]:
        writer.write_table(pa.table(cols, schema=SCHEMA))
    writer.close()
    return {"packets_total": total, "packets_roi": seq,
            "roles": dict(roles), "cmds": dict(cmds),
            "tensor_coverage_pct": round(100.0 * sum(
                v for k, v in roles.items()
                if k not in ("other", "program_image", "stack")) / max(seq, 1), 3)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run_dirs", nargs="+")
    ap.add_argument("--brk0", type=int, default=0,
                    help="initial program break of the original binary "
                         "(default: computed from the kernel in meta.json)")
    ap.add_argument("--maps", default="",
                    help="directory holding <run>/tensor_map.csv (default: the run dir)")
    opt = ap.parse_args()
    load_cmd_names()
    for d in map(Path, opt.run_dirs):
        t0, t1 = roi_window(d / "stats.txt")
        brk0 = opt.brk0
        if not brk0:
            from run_map import initial_brk, R
            kernel = json.loads((d / "meta.json").read_text())["plan"]["kernel"]
            brk0 = initial_brk(R.RV_BIN / kernel)
        mdir = Path(opt.maps) / d.name if opt.maps else d
        p2v = load_ptable(mdir / "ptable_ckpt" / "m5.cpt")
        rows, starts = load_map((Path(opt.maps) / d.name if opt.maps else d) / "tensor_map.csv", brk0)
        summary = {"roi_ticks": [t0, t1]}
        for lvl in ("l2", "l3"):
            summary[lvl] = extract(d / f"{lvl}_trace.trc.gz", d / f"{lvl}_roi.parquet",
                                   t0, t1, rows, starts, brk0, p2v)
        (d / "roi_summary.json").write_text(json.dumps(summary, indent=2))
        print(d.name, json.dumps({k: summary[k]["packets_roi"] for k in ("l2", "l3")}),
              "coverage l2", summary["l2"]["tensor_coverage_pct"], "%", flush=True)


if __name__ == "__main__":
    main()
