#!/usr/bin/env python3
"""
export_tree.py - turn the learned decision trees (train_policy.py) into C++
for the gem5 TensorAwareRP policy: one function per cache level,
    inline bool taTreeL2(const int *x) / taTreeL3(const int *x)
returning true = "keep" when the leaf's P(keep) >= --thr (same rule as
replay_policy.py). x[] follows the feature order in <policy>/metrics.json.
Also checks the C++ logic against sklearn: a Python transcription of the
generated if/else is evaluated on --check-rows feature rows and must agree
100%.
Usage: export_tree.py --policy results/policy_v3 --thr 0.3 --out FILE.hh
"""

import argparse
import json
import pickle
from pathlib import Path

import numpy as np
import pyarrow.parquet as pq

from train_policy import FEATURES as ALL   # order of x[] in tensor_aware_rp.cc


def emit(tree, feats, thr, node, depth, lines, py):
    ind = "    " * depth
    t = tree.tree_
    if t.children_left[node] == -1:
        v = t.value[node][0]
        p = v[1] / v.sum() if v.sum() else 0.0
        keep = "true" if p >= thr else "false"
        lines.append(f"{ind}return {keep};  // P(keep)={p:.3f} n={int(t.n_node_samples[node])}")
        py.append(f"{ind}return {p >= thr}")
        return
    f = t.feature[node]
    g = ALL.index(feats[f])          # index in the policy's full feature array
    # features are integers: x <= 2.5  <=>  x <= 2
    cut = int(np.floor(t.threshold[node]))
    lines.append(f"{ind}if (x[{g}] <= {cut}) {{  // {feats[f]}")
    py.append(f"{ind}if x[{g}] <= {cut}:")
    emit(tree, feats, thr, t.children_left[node], depth + 1, lines, py)
    lines.append(f"{ind}}} else {{")
    py.append(f"{ind}else:")
    emit(tree, feats, thr, t.children_right[node], depth + 1, lines, py)
    lines.append(f"{ind}}}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--policy", required=True)
    ap.add_argument("--thr", type=float, default=0.3, help="used unless metrics.json has thr_<level>")
    ap.add_argument("--out", required=True)
    ap.add_argument("--features", default="results/features_v2")
    ap.add_argument("--check-rows", type=int, default=2_000_000)
    ap.add_argument("--alt-l2-policy", default="", help="second L2 tree -> taTreeL2Alt")
    ap.add_argument("--alt-l2-thr", type=float, default=0.5)
    ap.add_argument("--alt-l2-features", default="")
    opt = ap.parse_args()
    pol = Path(opt.policy)
    meta = json.loads((pol / "metrics.json").read_text())
    out = ["// Generated by arch_study/trace_tools/export_tree.py - do not edit.",
           f"// policy: {pol.name}",
           f"// x[]: {', '.join(f'{i}={f}' for i, f in enumerate(ALL))}",
           "// trees use: " + "; ".join(f"{lv}: " + ", ".join(meta.get(f"features_{lv}", meta["features"]))
                                       + f" (P(keep) >= {meta.get(f'thr_{lv}', opt.thr)})" for lv in ("l2", "l3")),
           "#ifndef __MEM_CACHE_REPLACEMENT_POLICIES_TENSOR_AWARE_TREE_HH__",
           "#define __MEM_CACHE_REPLACEMENT_POLICIES_TENSOR_AWARE_TREE_HH__",
           "", "namespace gem5", "{", "namespace replacement_policy", "{", ""]
    for level in ("l2", "l3"):
        with open(pol / f"{level}_tree.pkl", "rb") as f:
            tree = pickle.load(f)
        feats = meta.get(f"features_{level}", meta["features"])
        thr = meta.get(f"thr_{level}", opt.thr)
        body, py = [], []
        emit(tree, feats, thr, 0, 1, body, py)
        out += [f"inline bool", f"taTree{level.upper()}(const int *x)", "{"] + body + ["}", ""]
        # self-check: python transcription vs sklearn on real feature rows
        ns = {}
        exec("def f(x):\n" + "\n".join(py), ns)
        rows = []
        files = sorted(Path(opt.features).glob(f"*/{level}_features.parquet")) or \
            sorted(Path("results/features_v2").glob(f"*/{level}_features.parquet"))
        for fp in files[::7]:
            rows.append(pq.read_table(fp, columns=ALL).to_pandas().to_numpy()[:200_000])
        X = np.concatenate(rows)[:opt.check_rows]
        sub = X[:, [ALL.index(f) for f in feats]]
        ref = tree.predict_proba(sub.astype(np.float32))[:, 1] >= thr
        got = np.array([ns["f"](r) for r in X.tolist()])
        agree = (ref == got).mean()
        print(f"{level}: {tree.get_n_leaves()} leaves, generated code agrees with sklearn on "
              f"{len(X)} rows: {100 * agree:.4f}%")
        if agree < 1:
            raise SystemExit("MISMATCH - not writing")
    if opt.alt_l2_policy:
        ap_ = Path(opt.alt_l2_policy)
        with open(ap_ / "l2_tree.pkl", "rb") as f:
            tree = pickle.load(f)
        feats = json.loads((ap_ / "metrics.json").read_text())["features"]
        body, py = [], []
        emit(tree, feats, opt.alt_l2_thr, 0, 1, body, py)
        out += [f"// alternative L2 tree: {ap_.name}, P(keep) >= {opt.alt_l2_thr}",
                "inline bool", "taTreeL2Alt(const int *x)", "{"] + body + ["}", ""]
        ns = {}
        exec("def f(x):\n" + "\n".join(py), ns)
        files = sorted(Path(opt.alt_l2_features).glob("*/l2_features.parquet"))
        X = np.concatenate([pq.read_table(fp, columns=ALL).to_pandas().to_numpy()[:200_000]
                            for fp in files[::7]])[:opt.check_rows]
        ref = tree.predict_proba(X[:, [ALL.index(f) for f in feats]].astype(np.float32))[:, 1] >= opt.alt_l2_thr
        got = np.array([ns["f"](r) for r in X.tolist()])
        print(f"l2 alt: {tree.get_n_leaves()} leaves, agrees on {len(X)} rows: {100 * (ref == got).mean():.4f}%")
        if (ref != got).any():
            raise SystemExit("MISMATCH - not writing")
    out += ["} // namespace replacement_policy", "} // namespace gem5", "",
            "#endif // __MEM_CACHE_REPLACEMENT_POLICIES_TENSOR_AWARE_TREE_HH__", ""]
    Path(opt.out).write_text("\n".join(out))
    print("wrote", opt.out)


if __name__ == "__main__":
    main()
