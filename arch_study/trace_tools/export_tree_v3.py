#!/usr/bin/env python3
"""
export_tree_v3.py - Step 7: learned L2 trees (train_l2_v3.py) -> C++ header
for gem5 TensorAwareRP (new file, does not touch tensor_aware_tree.hh).

Trees (all depth 6, P(keep) >= 0.3, class_weight balanced, min leaf 500):
  0 = trained without ViT   1 = without BERT   2 = without DLRM
  3 = without RNN-T         4 = trained on all 6 recorded workloads
so every workload of the comparison can be simulated with a tree that never
saw it (0-3), and the final rule uses tree 4.
x[] (15): the 10 TA features of tensor_aware_rp.cc, then pos16, plan16,
over_log2, inplan, prev_pf (train_l2_v3.py NEW).
Check: a Python transcription of each generated function must agree with
sklearn on every row of the cached feature arrays.
"""
import argparse
import pickle
from pathlib import Path

import numpy as np
from sklearn.tree import DecisionTreeClassifier

import train_l2_v3 as T

THR, DEPTH = 0.3, 6
FOLDS = ["vit", "bert", "dlrm", "rnnt"]


def emit(tree, feats, node, depth, cl, py):
    t = tree.tree_
    ind = "    " * depth
    if t.children_left[node] == -1:
        v = t.value[node][0]
        p = v[1] / v.sum() if v.sum() else 0.0
        k = p >= THR
        cl.append(f"{ind}return {'true' if k else 'false'};  // P(keep)={p:.3f}")
        py.append(f"{ind}return {k}")
        return
    f, th = t.feature[node], t.threshold[node]
    c = int(np.floor(th))           # integer features: x <= th  <=>  x <= floor(th)
    cl.append(f"{ind}if (x[{f}] <= {c}) {{  // {feats[f]}")
    py.append(f"{ind}if x[{f}] <= {c}:")
    emit(tree, feats, t.children_left[node], depth + 1, cl, py)
    cl.append(f"{ind}}} else {{")
    py.append(f"{ind}else:")
    emit(tree, feats, t.children_right[node], depth + 1, cl, py)
    cl.append(f"{ind}}}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--policy", default=str(T.R / "policy_l2_v3c"))
    ap.add_argument("--out", required=True)
    ap.add_argument("--per-run", type=int, default=300_000)
    o = ap.parse_args()
    out = Path(o.out)
    if out.exists():
        raise SystemExit(f"{out} exists")
    feats = T.OLD + T.NEW
    cache = T.R / "policy_l2_v3_cache"
    trees = [pickle.load(open(Path(o.policy) / f"tree_{n}_d{DEPTH}.pkl", "rb")) for n in FOLDS]
    # tree 4: all six workloads (same sampling as the folds)
    rng = np.random.default_rng(0)
    Xs, ys = [], []
    for n in T.RUNS:
        z = np.load(cache / f"{n}.npz")
        idx = np.flatnonzero(z["w"] > 0)
        if len(idx) > o.per_run:
            idx = np.sort(rng.choice(idx, o.per_run, replace=False))
        Xs.append(z["X"][idx]); ys.append(z["y"][idx])
    m = DecisionTreeClassifier(max_depth=DEPTH, min_samples_leaf=500,
                               class_weight="balanced", random_state=0)
    m.fit(np.concatenate(Xs), np.concatenate(ys))
    pickle.dump(m, open(Path(o.policy) / f"tree_all_d{DEPTH}.pkl", "wb"))
    trees.append(m)
    hdr = ["// Generated by arch_study/trace_tools/export_tree_v3.py - do not edit.",
           "// Step 7 learned L2 trees; x[]: " + ", ".join(f"{i}={f}" for i, f in enumerate(feats)),
           "// trees: 0 no-ViT, 1 no-BERT, 2 no-DLRM, 3 no-RNN-T, 4 all (P(keep) >= 0.3)",
           "#ifndef __MEM_CACHE_REPLACEMENT_POLICIES_TENSOR_AWARE_TREE_V3_HH__",
           "#define __MEM_CACHE_REPLACEMENT_POLICIES_TENSOR_AWARE_TREE_V3_HH__",
           "", "namespace gem5", "{", "namespace replacement_policy", "{", ""]
    for i, tr in enumerate(trees):
        cl, py = [], []
        emit(tr, feats, 0, 1, cl, py)
        hdr += ["inline bool", f"taTreeL2V3_{i}(const int *x)", "{"] + cl + ["}", ""]
        ns = {}
        exec("def f(x):\n" + "\n".join(py), ns)
        for n in T.RUNS:
            z = np.load(cache / f"{n}.npz")
            X = z["X"]
            sk = tr.predict_proba(X)[:, 1] >= THR
            sub = np.random.default_rng(1).choice(len(X), min(200_000, len(X)), replace=False)
            mine = np.array([ns["f"](X[j].astype(int).tolist()) for j in sub])
            assert (mine == sk[sub]).all(), f"tree {i} mismatch on {n}"
        print(f"tree {i}: {tr.get_n_leaves()} leaves, C++ == sklearn on all runs", flush=True)
    hdr += ["inline bool", "taTreeL2V3(int which, const int *x)", "{",
            "    switch (which) {"]
    hdr += [f"      case {i}: return taTreeL2V3_{i}(x);" for i in range(len(trees))]
    hdr += ["      default: return true;", "    }", "}", "",
            "} // namespace replacement_policy", "} // namespace gem5", "",
            "#endif // __MEM_CACHE_REPLACEMENT_POLICIES_TENSOR_AWARE_TREE_V3_HH__", ""]
    out.write_text("\n".join(hdr))
    print("wrote", out)


if __name__ == "__main__":
    main()
